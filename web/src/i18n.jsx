const I18nContext = createContext(null);

function interpolate(s, vars) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
}

// Standalone translator for components that must render in a FIXED language
// regardless of the app-wide setting (e.g. the English-only kiosk screen).
export function translate(s, lang = "ar", vars) {
  return interpolate(lang === "ar" ? s : (AR_TO_EN[s] ?? s), vars);
}

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("lang") || "ar");
  // Set before the first request goes out, not in the effect — otherwise the
  // mount-time fetches would carry the previous language.
  setApiLang(lang);
  useEffect(() => {
    setApiLang(lang);
    localStorage.setItem("lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    // Title comes from the stored app identity; IdentityProvider refines it
    // once loaded, so this is only the neutral default.
    if (!document.title || /^(Analytics|لوحة التحليلات)/.test(document.title)) {
      document.title = lang === "ar" ? "لوحة التحليلات" : "Analytics";
    }
  }, [lang]);
  const t = (s, vars) => interpolate(lang === "ar" ? s : (AR_TO_EN[s] ?? s), vars);
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
export default I18nProvider;
